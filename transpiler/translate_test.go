package transpiler

import (
	"fmt"
	"strings"
	"sync"
	"testing"
)

func TestTranslate(t *testing.T) {

	// Define a slice of test cases
	testCases := []struct {
		name     string
		input    string
		expected string
	}{

		{
			name:     "Simple CREATE TABLE with AUTO_INCREMENT",
			input:    "CREATE TABLE users (id INT AUTO_INCREMENT PRIMARY KEY)",
			expected: "CREATE TABLE users (id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY)",
		},
		{
			name:     "CREATE TABLE without AUTO_INCREMENT",
			input:    "CREATE TABLE orders (order_id INT PRIMARY KEY)",
			expected: "CREATE TABLE orders (order_id INT PRIMARY KEY)",
		},
		{
			name:     "CREATE TABLE with multiple columns",
			input:    "CREATE TABLE products (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(255))",
			expected: "CREATE TABLE products (id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, name TEXT(255))",
		},
		{
			name:     "CREATE TABLE with foreign key",
			input:    "CREATE TABLE orders (order_id INT PRIMARY KEY, user_id INT, FOREIGN KEY (user_id) REFERENCES users(id))",
			expected: "CREATE TABLE orders (order_id INT PRIMARY KEY, user_id INT, FOREIGN KEY (user_id) REFERENCES users (id))",
		},
		{
			name:     "SELECT with newlines",
			input:    "SELECT '\n' FROM users WHERE id = 1\n",
			expected: "SELECT '\n' FROM users WHERE id = 1",
		},
		{
			name:     "multiple statements",
			input:    "CREATE TABLE users (id INT AUTO_INCREMENT PRIMARY KEY); \n SELECT * FROM users WHERE id = 1",
			expected: "CREATE TABLE users (id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY)",
		},
		{
			name:     "XOR expands to DuckDB boolean form",
			input:    "SELECT i FROM t WHERE i XOR i",
			expected: "SELECT i FROM t WHERE ((i) AND NOT (i)) OR (NOT (i) AND (i))",
		},
		{
			name:     "nested XOR does not emit XOR keyword",
			input:    "SELECT i XOR i XOR i FROM t",
			expected: "SELECT (((i AND (NOT i)) OR ((NOT i) AND i)) AND NOT (i)) OR (NOT ((i AND (NOT i)) OR ((NOT i) AND i)) AND (i)) FROM t",
		},
		{
			name:     "CHAR_LENGTH becomes DuckDB LENGTH",
			input:    "SELECT CHAR_LENGTH(s) FROM t",
			expected: "SELECT LENGTH(s) FROM t",
		},
		{
			name:     "CHAR_LENGTH inside AVG does not emit CHAR_LENGTH",
			input:    "SELECT FLOOR(i), AVG(CHAR_LENGTH(s)) FROM mytable mt GROUP BY 1 ORDER BY FLOOR(i) DESC",
			expected: "SELECT FLOOR(i), AVG(LENGTH(s)) FROM mytable AS mt GROUP BY 1 ORDER BY FLOOR(i) DESC",
		},
		{
			name:     "FORMAT two-arg uses DuckDB fmt grouping",
			input:    "SELECT FORMAT(i, 3) FROM mytable",
			expected: "SELECT FORMAT('{:,.3f}', i) FROM mytable",
		},
		{
			name:     "FORMAT with da_DK swaps grouping separators",
			input:    "SELECT FORMAT(i, 3, 'da_DK') FROM mytable",
			expected: "SELECT REPLACE(REPLACE(REPLACE(FORMAT('{:,.3f}', i), ',', '\x01'), '.', ','), '\x01', '.') FROM mytable",
		},
		{
			name:     "aggregate without GROUP BY wraps non-agg columns",
			input:    "SELECT pk1, SUM(c1) FROM two_pk WHERE pk1 = 0",
			expected: "SELECT ANY_VALUE(pk1), SUM(c1) FROM two_pk WHERE pk1 = 0",
		},
		{
			name:     "explicit GROUP BY is left alone",
			input:    "SELECT pk1, SUM(c1) FROM two_pk GROUP BY pk1",
			expected: "SELECT pk1, SUM(c1) FROM two_pk GROUP BY pk1",
		},
		{
			name:     "FIND_IN_SET becomes list_position",
			input:    "SELECT FIND_IN_SET(s, 'first_row,second_row,third_row') FROM mytable",
			expected: "SELECT COALESCE(LIST_POSITION(STRING_SPLIT('first_row,second_row,third_row', ','), s), 0) FROM mytable",
		},
		{
			name:     "SUBSTRING_INDEX positive count",
			input:    "SELECT SUBSTRING_INDEX(s, 'd', 1) FROM mytable",
			expected: "SELECT CASE WHEN 1 = 0 THEN '' WHEN 1 > 0 THEN ARRAY_TO_STRING(LIST_SLICE(STRING_SPLIT(s, 'd'), 1, 1), 'd') ELSE ARRAY_TO_STRING(LIST_SLICE(STRING_SPLIT(s, 'd'), LEN(STRING_SPLIT(s, 'd')) + 1 + 1, LEN(STRING_SPLIT(s, 'd'))), 'd') END FROM mytable",
		},
		{
			name:     "HOUR casts datetime string to timestamp",
			input:    "SELECT HOUR('2007-12-11 20:21:22') FROM mytable",
			expected: "SELECT HOUR(CAST('2007-12-11 20:21:22' AS TIMESTAMP)) FROM mytable",
		},
		{
			name:     "ELT becomes list_extract",
			input:    "SELECT ELT(i, 'a', 'b') FROM mytable",
			expected: "SELECT LIST_EXTRACT(['a', 'b'], i) FROM mytable",
		},
		{
			name:     "FIELD becomes list_position",
			input:    "SELECT FIELD(i, '1', '2', '3') FROM mytable",
			expected: "SELECT COALESCE(LIST_POSITION(['1', '2', '3'], i), 0) FROM mytable",
		},
		{
			name:     "ADDDATE interval becomes date plus interval",
			input:    "SELECT ADDDATE(da, INTERVAL 1 DAY) FROM typestable",
			expected: "SELECT da + INTERVAL '1' DAY FROM typestable",
		},
		{
			name:     "ADDDATE days becomes date plus interval day",
			input:    "SELECT ADDDATE(da, 1) FROM typestable",
			expected: "SELECT da + INTERVAL 1 DAY FROM typestable",
		},
		{
			name:     "CONV 10 to 2 uses fmt binary",
			input:    "SELECT CONV(i, 10, 2) FROM mytable",
			expected: "SELECT FORMAT('{:b}', i) FROM mytable",
		},
		{
			name:     "BIT_LENGTH is octet_length times 8",
			input:    "SELECT BIT_LENGTH(i) FROM mytable",
			expected: "SELECT OCTET_LENGTH(CAST(i AS TEXT)) * 8 FROM mytable",
		},
		{
			name:     "OCTET_LENGTH becomes octet_length",
			input:    "SELECT OCTET_LENGTH(s) FROM mytable",
			expected: "SELECT OCTET_LENGTH(s) FROM mytable",
		},
		{
			name:     "OCTET_LENGTH keeps UTF-8 as bytes",
			input:    "SELECT OCTET_LENGTH('中') FROM mytable",
			expected: "SELECT OCTET_LENGTH('中') FROM mytable",
		},
		{
			name:     "UNHEX becomes from_hex",
			input:    "SELECT UNHEX(s) FROM mytable",
			expected: "SELECT FROM_HEX(s) FROM mytable",
		},
		{
			name:     "MD5 casts integers to text",
			input:    "SELECT MD5(i) FROM mytable",
			expected: "SELECT MD5(CAST(i AS TEXT)) FROM mytable",
		},
		{
			name:     "SHA2 256 becomes sha256 of text",
			input:    "SELECT SHA2(i, 256) FROM mytable",
			expected: "SELECT SHA256(CAST(i AS TEXT)) FROM mytable",
		},
		{
			name:     "ASCII is first byte",
			input:    "SELECT ASCII(s) FROM mytable",
			expected: "SELECT GET_BYTE(CAST(s AS BLOB), 0) FROM mytable",
		},
	}

	// Loop over each test case
	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			result, err := TranslateWithSQLGlot(tc.input)
			if err != nil {
				t.Errorf("translate(%q) returned an error: %v", tc.input, err)
			}

			trimmedResult := strings.TrimSpace(result)
			fmt.Println("trimmedResult:", trimmedResult)
			if trimmedResult != tc.expected {
				t.Errorf("translate(%q) = %v; want %v", tc.input, trimmedResult, tc.expected)
			}
		})
	}
}

func TestTranslateConcurrent(t *testing.T) {
	concurrency := 1000
	wg := sync.WaitGroup{}
	wg.Add(concurrency)

	for i := 0; i < concurrency; i++ {
		go func(i int) {
			defer wg.Done()

			sql := fmt.Sprintf("SELECT * FROM users WHERE id = %d", i)
			expectedSQL := sql

			translatedSQL, err := TranslateWithSQLGlot(sql)
			if err != nil {
				t.Errorf("translate(%q) returned an error: %v", sql, err)
			}
			if translatedSQL != expectedSQL {
				t.Errorf("translate(%q) = %v; want %v", sql, translatedSQL, expectedSQL)
			}
		}(i)
	}

	wg.Wait()
}
